import unittest
from unittest.mock import Mock, call, patch

import requests

import generate_html_report as report


def response(data=None, status=200):
    result = Mock(status_code=status)
    result.json.return_value = data
    if status >= 400:
        result.raise_for_status.side_effect = requests.HTTPError(f'HTTP {status}')
    return result


class RenderingTests(unittest.TestCase):
    def test_escape_all_api_fields(self):
        payload = '<img src=x onerror="alert(1)"> & \'test\''
        coin = dict(symbol=payload, name=payload, image='https://example.com/" onerror="x',
                    current_price=1, price_change_percentage_24h=1)
        html = report.generate_html({}, [coin], [{'name': payload}],
                                    [{'item': {'name': payload, 'symbol': payload, 'market_cap_rank': payload}}])
        self.assertNotIn(payload, html)
        self.assertIn(report.text(payload), html)
        self.assertIn(report.text(payload.upper()), html)
        self.assertIn('https://example.com/&quot; onerror=&quot;x', html)
        self.assertNotIn('src="https://example.com/" onerror=', html)

    def test_image_schemes(self):
        for value in ['javascript:alert(1)', 'data:image/svg+xml,x', '//example.com/x', None, 'http://[']:
            with self.subTest(value=value):
                self.assertEqual(report.image_url(value), '')
        self.assertEqual(report.image_url('http://example.com/x?a=1&b=2'), 'http://example.com/x?a=1&amp;b=2')
        self.assertEqual(report.image_url('https://example.com/x'), 'https://example.com/x')

    def test_movers_and_counts(self):
        coins = [{'symbol': str(value), 'price_change_percentage_24h': value}
                 for value in [2, -1, 0, None, -8, 5]]
        gainers, losers = report.movers(coins)
        self.assertEqual([report.coin_change(c) for c in gainers], [5, 2])
        self.assertEqual([report.coin_change(c) for c in losers], [-8, -1])
        html = report.generate_html({}, coins, [], [])
        self.assertIn('2 🟢', html)
        self.assertIn('2 🔴', html)
        self.assertNotIn('+-', html)
        self.assertIn('0.00%', html)
        self.assertLess(report.mover_rows(losers).index('-8.00%'), report.mover_rows(losers).index('-1.00%'))

    def test_empty_null_and_zero(self):
        self.assertEqual(report.movers([]), ([], []))
        self.assertEqual(report.mover_rows([]), '')
        self.assertEqual(report.change_text(0), '0.00%')
        html = report.generate_html({'total_market_cap': None, 'total_volume': None,
                                     'market_cap_percentage': None,
                                     'market_cap_change_percentage_24h_usd': None}, [], [], [])
        self.assertIn('0 🔴', html)
        self.assertIn('0 🟢', html)
        self.assertIn('GMT+8', html)
        self.assertIn('Data provided by CoinGecko | Report generated by OpenClaw', html)
        self.assertIn('Updated hourly | Last update:', html)


class FetchTests(unittest.TestCase):
    @patch.object(report.time, 'sleep')
    @patch.object(report.requests, 'get')
    def test_retry_429_and_server_errors(self, get, sleep):
        get.side_effect = [response(status=429), response(status=503), response({'ok': True})]
        self.assertEqual(report.fetch_json('/global'), {'ok': True})
        self.assertEqual(sleep.call_args_list, [call(30), call(60)])
        self.assertEqual(get.call_count, 3)
        self.assertEqual(get.call_args.kwargs['timeout'], 30)

    @patch.object(report.time, 'sleep')
    @patch.object(report.requests, 'get')
    def test_retry_exhaustion(self, get, sleep):
        for status in [429, 500]:
            with self.subTest(status=status):
                get.reset_mock()
                sleep.reset_mock()
                get.return_value = response(status=status)
                with self.assertRaisesRegex(RuntimeError, f'CoinGecko /global: HTTP {status}'):
                    report.fetch_json('/global')
                self.assertEqual(get.call_count, 4)
                self.assertEqual(sleep.call_args_list, [call(30), call(60), call(120)])

    @patch.object(report.time, 'sleep')
    @patch.object(report.requests, 'get')
    def test_non_retryable_errors(self, get, sleep):
        get.return_value = response(status=404)
        with self.assertRaisesRegex(RuntimeError, 'HTTP 404'):
            report.fetch_json('/global')
        sleep.assert_not_called()
        for error in [requests.ConnectionError('offline'), requests.Timeout('timed out')]:
            get.side_effect = error
            with self.assertRaisesRegex(RuntimeError, 'CoinGecko /global:'):
                report.fetch_json('/global')

    @patch.object(report.requests, 'get')
    def test_invalid_json(self, get):
        get.return_value = response()
        get.return_value.json.side_effect = ValueError('invalid JSON')
        with self.assertRaisesRegex(RuntimeError, 'CoinGecko /global: invalid JSON'):
            report.fetch_json('/global')

    @patch.object(report.requests, 'get')
    def test_valid_empty_responses(self, get):
        get.side_effect = [response({'data': {}}), response([]), response([]), response({'coins': []})]
        self.assertEqual(report.fetch_data(), ({}, [], [], []))

    @patch.object(report.requests, 'get')
    def test_invalid_shapes(self, get):
        valid = [{'data': {}}, [], [], {'coins': []}]
        for index, invalid in [(0, []), (0, {'data': None}), (1, {}), (1, [None]),
                               (2, {}), (3, {'coins': {}}), (3, {'coins': [{'item': None}]})]:
            with self.subTest(index=index, invalid=invalid):
                data = valid.copy()
                data[index] = invalid
                get.side_effect = [response(item) for item in data]
                with self.assertRaisesRegex(RuntimeError, 'CoinGecko .*expected'):
                    report.fetch_data()


if __name__ == '__main__':
    unittest.main()
